#!/usr/bin/env python3
"""Generate the maintenance demand for each planning scenario.

    python generate_scenario_jobs.py                     # all scenarios
    python generate_scenario_jobs.py --only MAINTENANCE_BACKLOG

WHY THIS EXISTS
---------------
Scenario demand used to be scaled by cloning: an existing job was copied and
only its `id` changed. Every clone therefore kept its original's section, its
km_from/km_to footprint and its exclusive resource id, which means

  * the clone and its original overlap spatially, so `pairwise_compatible`
    refuses them in one block, forever;
  * they hold the same exclusive resource, so the solver cannot even run them
    in the same time slot on different sections.

A cloned job is not additional demand. It is an object that can never be
scheduled alongside the job it was copied from, and it drags the whole
higher-demand scenario away from anything a division would recognise. The two
scenarios that exist specifically to show the method under load —
MAINTENANCE_BACKLOG and MULTIPLE_DEPARTMENT_REQUESTS — were the two most
corrupted by it.

The fix is not a new distribution. It is to use the demand model the base
dataset already uses: Poisson arrivals whose rate comes from the asset
inventory and the maintenance periodicity (see dsgen/demand.py and
docs/methodology.md). Each scenario is generated by that same function with the
scenario's own declared parameters, so extra demand arrives as genuinely new
jobs with their own locations, footprints, durations, resources and due dates.

REPRODUCIBILITY
---------------
Every scenario is generated from the SAME seed as the base dataset. That is
deliberate: with the rate parameters equal, an identical seed reproduces the
base job set exactly, so a scenario that only changes traffic or urgency is a
controlled variation on the same maintenance programme rather than a different
one. Scenarios that raise `demand_scale` necessarily draw a different Poisson
realisation; those are independent higher-demand instances, and the seed, the
parameters and the realised job count are all written to
dataset/scenarios/scenario_jobs_manifest.csv.

The corridor is rebuilt from the PROCESSED tables, not from the 98 MB raw
sources: stations.csv and sections.csv are themselves deterministic outputs of
those sources, so this stays reproducible without re-parsing them.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dsgen import demand, network, scenarios  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_corridor_from_processed(processed_dir):
    """Rebuild the minimum Corridor the demand model needs.

    demand.generate_jobs touches only: cor.stations (code, is_junction) and
    cor.sections (section_id, from_code, to_code, line, length_km, electrified).
    Nothing else is read, so nothing else is reconstructed.
    """
    with open(os.path.join(processed_dir, "stations.csv"), encoding="utf-8") as f:
        st = [network.Station(code=r["station_code"], name=r["station_name"],
                              lat=float(r["latitude"]), lon=float(r["longitude"]),
                              zone=r["zone"], state=r["state"], seq=int(r["seq"]),
                              is_junction=bool(int(r["is_junction"])))
              for r in csv.DictReader(f)]
    with open(os.path.join(processed_dir, "sections.csv"), encoding="utf-8") as f:
        sec = [network.SectionLine(
            section_id=r["section_id"], from_code=r["from_station_code"],
            to_code=r["to_station_code"], line=r["line"],
            length_km=float(r["length_km"]), tracks=int(r["tracks"]),
            electrified=bool(int(r["electrified"])),
            headway_min=int(r["headway_min"]),
            degraded_factor=float(r["degraded_factor"]),
            support_trains=int(r["support_trains"]),
            track_source=r["track_source"]) for r in csv.DictReader(f)]
    return network.Corridor(stations=st, sections=sec)


def write_csv(path, rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()), extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default=os.path.join(ROOT, "dataset"))
    ap.add_argument("--config", default=os.path.join(ROOT, "config"))
    ap.add_argument("--only", default=None, help="generate one scenario only")
    args = ap.parse_args()

    processed = os.path.join(args.dataset, "processed")
    out_dir = os.path.join(args.dataset, "scenarios", "jobs")

    with open(os.path.join(args.config, "activities.yaml"), encoding="utf-8") as f:
        activities = yaml.safe_load(f)
    with open(os.path.join(args.config, "assumptions.yaml"), encoding="utf-8") as f:
        assumptions = yaml.safe_load(f)
    with open(os.path.join(args.config, "corridor.yaml"), encoding="utf-8") as f:
        corridor_cfg = yaml.safe_load(f)
    with open(os.path.join(args.dataset, "metadata", "manifest.json"),
              encoding="utf-8") as f:
        manifest = json.load(f)

    horizon = corridor_cfg["horizon"]["days"]
    seed = int(manifest["seed"])          # the base dataset's seed, reused
    size = manifest["size"]
    base_target = {"small": 40, "medium": 180, "large": 400}[size]

    cor = load_corridor_from_processed(processed)
    print(f"corridor rebuilt from processed tables: "
          f"{len(cor.stations)} stations, {len(cor.sections)} section-lines")
    print(f"base seed={seed} size={size} horizon={horizon}d "
          f"base target_jobs={base_target}\n")

    manifest_rows = []
    for name, sc in scenarios.SCENARIOS.items():
        if args.only and name != args.only:
            continue
        demand_scale = float(sc.get("demand_scale", 1.0))
        target = int(round(base_target * demand_scale))

        jobs = demand.generate_jobs(
            cor, activities, assumptions, horizon, seed,
            backlog_multiplier=sc.get("backlog", 1.0),
            demand_scale=demand_scale,
            uncertainty_scale=sc.get("uncertainty_scale", 1.0),
            target_jobs=target)

        # Urgency is applied exactly as generate_dataset.py applies it, so a
        # scenario job file is what the base generator would have produced had
        # it been run for that scenario.
        shift = int(sc.get("urgency_shift", 0) or 0)
        if shift:
            for j in jobs:
                j.due_day = max(-14, j.due_day + shift)

        rows = demand.job_rows(jobs)
        path = os.path.join(out_dir, f"jobs_{name}.csv")
        write_csv(path, rows)

        by_dept = {d: sum(1 for j in jobs if j.dept == d)
                   for d in ("ENGG", "SNT", "TRD")}
        overdue = sum(1 for j in jobs if j.due_day < 0)
        manifest_rows.append({
            "scenario": name, "seed": seed, "target_jobs": target,
            "generated_jobs": len(jobs),
            "demand_scale": demand_scale,
            "backlog_multiplier": sc.get("backlog", 1.0),
            "uncertainty_scale": sc.get("uncertainty_scale", 1.0),
            "urgency_shift": shift,
            "jobs_ENGG": by_dept["ENGG"], "jobs_SNT": by_dept["SNT"],
            "jobs_TRD": by_dept["TRD"], "overdue_jobs": overdue,
            "file": os.path.relpath(path, args.dataset).replace("\\", "/"),
            "method": "dsgen.demand.generate_jobs "
                      "(poisson_from_periodicity), identical to the base "
                      "dataset; no cloning",
        })
        print(f"  {name:30s} seed={seed} target={target:4d} "
              f"jobs={len(jobs):4d} "
              f"(ENGG={by_dept['ENGG']} SNT={by_dept['SNT']} "
              f"TRD={by_dept['TRD']}, overdue={overdue})")

    mpath = os.path.join(args.dataset, "scenarios", "scenario_jobs_manifest.csv")
    write_csv(mpath, manifest_rows)
    print(f"\nscenario -> seed -> job count written to:\n  {mpath}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
